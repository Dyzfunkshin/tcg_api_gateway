"""Create the key for an app-key client and store it in Bitwarden (PLAN.md section 6.4).

Usage (from a venv with bitwarden-sdk, as gateway-deploy with write on api-gateway):
  python tools/create_app_key.py POKE_GUIDE_DEV            # print the plan; contacts nothing
  python tools/create_app_key.py POKE_GUIDE_DEV --apply    # generate, store, print the SHA-256
  python tools/create_app_key.py POKE_GUIDE_DEV --apply --rotate   # replace an existing key

The key is 32 random bytes as 64 hex characters, stored as TCG_GATEWAY_APP_KEY_<APP> in
the Bitwarden project api-gateway. Only its SHA-256 is printed: that hash goes in the
client's `keySha256` in src/clients.js. The key itself never reaches output or logs.
"""

import argparse
import hashlib
import re
import secrets
import sys

from push_secrets import API_GATEWAY_PROJECT_ID, SecretStoreError, open_bitwarden_store

APP_KEY_BYTES = 32
APP_NAME = re.compile(r"^[A-Z][A-Z0-9_]{1,40}$")


def secret_name(app: str) -> str:
    return "TCG_GATEWAY_APP_KEY_" + app


def key_sha256(key: str) -> str:
    """The hash the Worker compares: SHA-256 of the key text, as hex."""
    return hashlib.sha256(key.encode("utf-8")).hexdigest()


def create_app_key(store, app: str, rotate: bool) -> str:
    """Store a fresh key for `app` and return its SHA-256. Refuses to replace one unless `rotate`."""
    name = secret_name(app)
    if store.get(name) is not None and not rotate:
        raise SecretStoreError(f"{name} already exists; pass --rotate to replace it (the old key stops working at the next deploy)")
    key = secrets.token_hex(APP_KEY_BYTES)
    store.put(name, key, API_GATEWAY_PROJECT_ID, "Gateway app key; generated by tools/create_app_key.py (PLAN.md 6.4)")
    return key_sha256(key)


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("app", help="the app's name in SCREAMING_SNAKE_CASE, e.g. POKE_GUIDE_DEV")
    parser.add_argument("--apply", action="store_true", help="generate and store the key (default: print the plan)")
    parser.add_argument("--rotate", action="store_true", help="replace an existing key")
    return parser.parse_args(argv)


def main(argv=None, *, open_store=open_bitwarden_store) -> int:
    args = parse_args(argv)
    if not APP_NAME.match(args.app):
        print(f"app name {args.app!r} must be SCREAMING_SNAKE_CASE", file=sys.stderr)
        return 2
    name = secret_name(args.app)
    if not args.apply:
        print(f"plan: generate {APP_KEY_BYTES} random bytes -> Bitwarden {name} (project api-gateway); print its SHA-256")
        return 0
    try:
        digest = create_app_key(open_store(), args.app, args.rotate)
    except SecretStoreError as error:
        print(f"failed: {error}", file=sys.stderr)
        return 1
    print(f"stored   {name} in Bitwarden project api-gateway")
    print(f"keySha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
